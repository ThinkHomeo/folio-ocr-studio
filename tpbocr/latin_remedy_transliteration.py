def clean_remedy_name_hi(latin_name):
    """Convert any Latin remedy name to pure Devanagari transliteration."""
    if not latin_name:
        return ""
    import re
    # Strip oorep notes like (+ -ac.), (Alte Abk.) and secondary aliases like '+ Dubo-M.'
    clean_latin = re.sub(r"\([^)]*\)", "", latin_name)
    if "+" in clean_latin and not any(k in clean_latin.lower() for k in ["carbonicum", "muriaticum", "sulphuricum"]):
        clean_latin = clean_latin.split("+")[0]
    clean_latin = clean_latin.strip()
    words = clean_latin.split()
    dev_words = []
    for w in words:
        wl = w.strip(".,()[]&+-").lower()
        if wl in REMEDY_WORD_MAP:
            dev_words.append(REMEDY_WORD_MAP[wl])
        elif w in ["&", "+", "/"]:
            dev_words.append("एवं")
        elif wl:
            dev_words.append(w)
    return " ".join(dev_words).strip()
